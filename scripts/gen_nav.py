"""Regenerate the `nav:` section of mkdocs.yml from the files in bansuri-mastery/.

Usage: python scripts/gen_nav.py [--check]
With --check, exit 1 if mkdocs.yml is out of date instead of rewriting it.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "bansuri-mastery")
CONFIG = os.path.join(ROOT, "mkdocs.yml")
BEGIN, END = "# BEGIN NAV (generated by scripts/gen_nav.py)", "# END NAV"


def md(folder):
    path = os.path.join(DOCS, folder)
    return sorted(f for f in os.listdir(path) if f.endswith(".md") and f != "README.md")


def natural(name):
    return [int(p) if p.isdigit() else p for p in re.split(r"(\d+)", name)]


def raga_order():
    # Follow the order of the raga index table.
    text = open(os.path.join(DOCS, "ragas", "README.md"), encoding="utf-8").read()
    found = re.findall(r"\]\(([a-z]+\.md)\)", text)
    seen = []
    for f in found:
        if f not in seen and os.path.exists(os.path.join(DOCS, "ragas", f)):
            seen.append(f)
    rest = [f for f in md("ragas") if f not in seen]
    return seen + rest


def build():
    lines = ["nav:"]
    add = lines.append
    add("  - Home: README.md")
    add("  - Start here:")
    for f in ["00-MASTERY-MAP.md", "05-CONVENTIONS-AND-NOTATION-KEY.md", "03-PROGRESS-TRACKER.md", "tools/index.md"]:
        add(f"    - {f}")
    add("  - Roadmap:")
    add("    - phases/README.md")
    for f in md("phases"):
        add(f"    - phases/{f}")
    add("  - Lessons:")
    add("    - lessons/README.md")
    for f in md("lessons"):
        add(f"    - lessons/{f}")
    add("  - Exercises:")
    add("    - exercises/README.md")
    for f in md("exercises"):
        add(f"    - exercises/{f}")
    add("  - Ragas:")
    add("    - ragas/README.md")
    for f in raga_order():
        add(f"    - ragas/{f}")
    add("  - Milestones:")
    add("    - projects/README.md")
    for f in sorted(md("projects"), key=natural):
        add(f"    - projects/{f}")
    add("  - Troubleshooting:")
    add("    - troubleshooting/README.md")
    for f in md("troubleshooting"):
        add(f"    - troubleshooting/{f}")
    add("  - Reference:")
    for f in ["02-RESOURCE-LIBRARY.md", "08-LISTENING-LIBRARY.md", "09-SONG-SUGGESTIONS.md", "06-GLOSSARY.md"]:
        add(f"    - {f}")
    add("    - Knowledge tree:")
    add("      - 01-KNOWLEDGE-TREE.md")
    add("      - knowledge-tree/README.md")
    for f in md("knowledge-tree"):
        add(f"      - knowledge-tree/{f}")
    add("    - 07-QUALITY-REPORT.md")
    return "\n".join(lines)


def main():
    cfg = open(CONFIG, encoding="utf-8").read()
    start, end = cfg.index(BEGIN) + len(BEGIN), cfg.index(END)
    new = cfg[:start] + "\n" + build() + "\n" + cfg[end:]
    if "--check" in sys.argv:
        if new != cfg:
            print("mkdocs.yml nav is out of date: run python scripts/gen_nav.py")
            sys.exit(1)
        print("nav up to date")
        return
    with open(CONFIG, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print("nav written")


if __name__ == "__main__":
    main()
