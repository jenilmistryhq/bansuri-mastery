"""Build the single-file Practice Bench pages from the app's ES modules.

Sources (edit these):
  app/js/core/settings.js, theory.js, audio.js, notation.js, pitch.js, listen.js, live.js
  app/js/bench/bench.js, bench.css, bench-tokens.css

Outputs (generated, do not edit):
  bansuri-mastery/tools/practice-bench.html   complete document (GitHub Pages docs site, offline use)
  bansuri-mastery/tools/interactive-flute.html claude.ai Artifact fragment (no doctype/html/head/body)

The bundler strips `import ... from` lines and leading `export` keywords, checks that no two
modules declare the same top-level name (they share one scope once bundled), and wraps
everything in one IIFE that mounts the bench.

Usage: python scripts/build_bench.py [--check]
With --check, exit 1 if either output is out of date instead of rewriting it.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JS = os.path.join(ROOT, "app", "js")
TOOLS = os.path.join(ROOT, "bansuri-mastery", "tools")
MODULES = ["core/settings.js", "core/theory.js", "core/audio.js", "core/notation.js", "core/pitch.js", "core/listen.js", "core/live.js", "bench/bench.js"]
OUT_FULL = os.path.join(TOOLS, "practice-bench.html")
OUT_FRAGMENT = os.path.join(TOOLS, "interactive-flute.html")

GENERATED = "<!-- Generated by scripts/build_bench.py from app/js/core and app/js/bench. Edit those files, not this one. -->"
FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Rozha+One&family=Hind:wght@400;500;600'
    '&family=JetBrains+Mono:wght@400;600&display=swap">'
)
IMPORT_RE = re.compile(r'^import\s+[^;]*\s+from\s+"[^"]+";\s*$')
EXPORT_RE = re.compile(r"^export\s+(?=(async\s+function|function|const|let|class)\b)")
DECL_RE = re.compile(r"^(?:async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)")


def read(rel):
    with open(os.path.join(JS, rel), encoding="utf-8") as fh:
        return fh.read()


def bundle_js():
    parts, seen = [], {}
    for rel in MODULES:
        lines = []
        for line in read(rel).splitlines():
            if IMPORT_RE.match(line):
                continue
            if line.startswith("import "):
                raise SystemExit(f"{rel}: unsupported import form: {line}")
            if line.startswith("export ") and not EXPORT_RE.match(line):
                raise SystemExit(f"{rel}: unsupported export form: {line}")
            line = EXPORT_RE.sub("", line)
            m = DECL_RE.match(line)
            if m:
                name = m.group(1)
                if name in seen:
                    raise SystemExit(f"duplicate top-level name '{name}' in {rel} and {seen[name]}")
                seen[name] = rel
            lines.append(line)
        parts.append(f"// ---- {rel} ----\n" + "\n".join(lines).strip() + "\n")
    js = "(() => {\n\"use strict\";\n" + "\n".join(parts) + '\nmountBench(document.getElementById("bench-root"), {});\n})();\n'
    if "</script" in js.lower():
        raise SystemExit("bundle contains '</script', which would end the inline script early")
    return js


def css():
    with open(os.path.join(JS, "bench", "bench-tokens.css"), encoding="utf-8") as fh:
        tokens = fh.read()
    return tokens.strip() + "\n" + read("bench/bench.css").strip() + "\n"


def body(footer_link):
    curriculum = '<a href="../">Bansuri Mastery curriculum</a>' if footer_link else "Bansuri Mastery curriculum"
    return (
        '<main class="bb-page">\n<div id="bench-root"></div>\n'
        f'<p>Part of the {curriculum}. Notation and fingerings follow <span class="bb-mono">05-CONVENTIONS-AND-NOTATION-KEY.md</span>.</p>\n'
        "</main>\n"
    )


def build_full(js, style):
    return (
        "<!doctype html>\n" + GENERATED + '\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
        "<title>Bansuri Practice Bench</title>\n"
        '<meta name="description" content="An interactive 6-hole bansuri: fingering chart, sargam player, tanpura, tala metronome, ear quiz and pitch checker.">\n'
        + FONTS + "\n<style>\n:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}\n"
        + style + "</style>\n</head>\n<body>\n" + body(True) + "<script>\n" + js + "</script>\n</body>\n</html>\n"
    )


def build_fragment(js, style):
    return (
        GENERATED + "\n<title>Bansuri Practice Bench</title>\n"
        '<meta name="claude:viewport-fit-sides" content="cover">\n'
        + FONTS + "\n<style>\n" + style + "</style>\n" + body(False) + "<script>\n" + js + "</script>\n"
    )


def main():
    js, style = bundle_js(), css()
    outputs = {OUT_FULL: build_full(js, style), OUT_FRAGMENT: build_fragment(js, style)}
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if old != text:
            stale.append(path)
            if "--check" not in sys.argv:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
                print("wrote", os.path.relpath(path, ROOT))
    if "--check" in sys.argv:
        if stale:
            print("Practice Bench outputs are out of date: run python scripts/build_bench.py")
            sys.exit(1)
        print("practice bench up to date")
    elif not stale:
        print("practice bench already up to date")


if __name__ == "__main__":
    main()
