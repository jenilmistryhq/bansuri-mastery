"""List every claim the curriculum marks as Uncertain or Disputed, for a teacher to review.

Writes TEACHER-REVIEW-CLAIMS.md at the repository root: one row per claim with the file, line and
the sentence, grouped by file in course order. `--check` fails if the file is out of date.
Usage: python scripts/review_claims.py [--check]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "bansuri-mastery")
OUT = os.path.join(ROOT, "TEACHER-REVIEW-CLAIMS.md")
MARK = re.compile(r"\*\*(Uncertain|Disputed)\b|\b(Uncertain|Disputed)[:.)]")
LEGEND = re.compile(r"^\|\s*\*\*(Uncertain|Disputed|Fact|Recommendation)\*\*\s*\|")
ORDER = ["", "lessons", "ragas", "exercises", "projects", "phases", "troubleshooting", "knowledge-tree", "tools"]


def files():
    out = []
    for d, _, fs in os.walk(DOCS):
        for f in fs:
            if f.endswith(".md"):
                rel = os.path.relpath(os.path.join(d, f), DOCS).replace(os.sep, "/")
                folder = rel.split("/")[0] if "/" in rel else ""
                out.append((ORDER.index(folder) if folder in ORDER else 99, rel))
    return [r for _, r in sorted(out)]


def clean(line):
    line = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", line.strip())
    line = line.replace("|", "/").strip("/ -")
    return line[:400] + (" ..." if len(line) > 400 else "")


def build():
    rows, total = [], 0
    for rel in files():
        with open(os.path.join(DOCS, rel), encoding="utf-8") as fh:
            # The legend rows that define the labels are not claims.
            hits = [(i + 1, l) for i, l in enumerate(fh) if MARK.search(l) and not LEGEND.match(l)]
        if not hits:
            continue
        rows.append(f"\n## [{rel}](bansuri-mastery/{rel})\n\n| Line | Claim | Your review |\n|---|---|---|")
        for n, l in hits:
            kind = "Disputed" if "Disputed" in l else "Uncertain"
            rows.append(f"| {n} | **{kind}:** {clean(l)} | |")
            total += 1
    head = ("# Claims to review\n\n"
            "Generated by `scripts/review_claims.py` from the curriculum. Do not edit by hand: correct the "
            "lesson itself, then run the script again.\n\n"
            f"The course marks **{total}** claims as **Uncertain** (not verified well enough) or **Disputed** "
            "(sources or traditions differ). A teacher's view settles most of them. For each, write in the last "
            "column: *confirmed*, *wrong: ...* with the correction, or *my tradition: ...*. See "
            "[TEACHER-REVIEW.md](TEACHER-REVIEW.md) for how to send notes.\n")
    return head + "\n".join(rows) + "\n"


def main():
    text = build()
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in sys.argv:
        if old.replace("\r\n", "\n") != text:
            print("TEACHER-REVIEW-CLAIMS.md is out of date: run python scripts/review_claims.py")
            sys.exit(1)
        print("claims list up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote TEACHER-REVIEW-CLAIMS.md:", text.count("\n| ") - text.count("| Line |"), "claims")


if __name__ == "__main__":
    main()
